import {
  Block,
  BlockItem,
  BlockItemContent,
  BlockItemHeader,
  BlockItemTitle,
} from "@/components/block";
import HeaderToggle from "@/components/service/header-toggle";
import { validateDomain } from "@/lib/helpers/validate-domain";
import { validatePort } from "@/lib/helpers/validate-port";
import { withForm } from "@/lib/hooks/use-app-form";
import { CheckCircleIcon, CircleSlashIcon, LockIcon } from "lucide-react";

const DomainPortBlock = withForm({
  defaultValues: {
    isPublic: true,
    domain: "",
    targetPort: "",
  },
  props: {
    autoGeneratedDomain: undefined as string | undefined,
    detectedPort: undefined as string | undefined,
  },
  render: function Render({ form, detectedPort, autoGeneratedDomain }) {
    return (
      <Block>
        <BlockItem>
          <BlockItemHeader>
            <BlockItemTitle>Domain</BlockItemTitle>
            <form.AppField
              name="isPublic"
              children={(field) => (
                <HeaderToggle
                  label="Private"
                  checked={!field.state.value}
                  onChange={(isPrivate) => {
                    const isPublic = !isPrivate;
                    if (!isPublic) {
                      form.setErrorMap({
                        onChange: { fields: { domain: undefined, targetPort: undefined } },
                      });
                    }
                    field.handleChange(isPublic);
                  }}
                />
              )}
            />
          </BlockItemHeader>
          <BlockItemContent>
            <form.Subscribe
              selector={(state) => ({ isPublic: state.values.isPublic })}
              children={({ isPublic }) => (
                <form.AppField
                  name="domain"
                  validators={{
                    onChange: ({ value }) => validateDomain({ value, isPublic }),
                  }}
                  children={(field) => (
                    <field.DomainInput
                      disabled={!isPublic}
                      fadeOnDisabled={!isPublic ? false : undefined}
                      data-private={!isPublic || undefined}
                      classNameInput="data-private:text-muted-foreground"
                      Icon={!isPublic ? LockIcon : undefined}
                      classNameIcon="text-muted-foreground"
                      field={field}
                      value={!isPublic ? "Private service" : field.state.value}
                      onBlur={!isPublic ? undefined : field.handleBlur}
                      onChange={
                        !isPublic
                          ? undefined
                          : (e) => {
                              field.handleChange(e.target.value);
                            }
                      }
                      placeholder="example.com"
                      autoCapitalize="off"
                      autoCorrect="off"
                      autoComplete="off"
                      spellCheck="false"
                      autoGeneratedDomain={!isPublic ? undefined : autoGeneratedDomain}
                    />
                  )}
                />
              )}
            />
          </BlockItemContent>
        </BlockItem>
        {/* Branch */}
        <BlockItem>
          <BlockItemHeader>
            <BlockItemTitle>Port</BlockItemTitle>
            <form.Subscribe
              selector={(state) => ({ isPublic: state.values.isPublic })}
              children={({ isPublic }) => {
                if (!isPublic) return null;
                return (
                  <div
                    data-detected={detectedPort !== undefined || undefined}
                    className="bg-warning/4-10 text-warning border-warning/4-10 data-detected:text-success data-detected:bg-success/4-10 data-detected:border-success/4-10 -my-1 ml-auto flex min-w-0 shrink items-center justify-start gap-1.5 rounded-full border px-2 py-0.5"
                  >
                    {detectedPort !== undefined ? (
                      <CheckCircleIcon className="-ml-0.75 size-3.5 shrink-0" />
                    ) : (
                      <CircleSlashIcon className="-ml-0.75 size-3.5 shrink-0" />
                    )}
                    <p className="min-w-0 shrink truncate text-sm leading-tight font-medium">
                      {detectedPort !== undefined ? (
                        <>
                          Detected: <span className="font-bold">{detectedPort}</span>
                        </>
                      ) : (
                        "Couldn't detect"
                      )}
                    </p>
                  </div>
                );
              }}
            />
          </BlockItemHeader>
          <BlockItemContent>
            <form.Subscribe
              selector={(state) => ({ isPublic: state.values.isPublic })}
              children={({ isPublic }) => (
                <form.AppField
                  name="targetPort"
                  validators={{
                    onChange: ({ value }) => validatePort({ value, isPublic }),
                  }}
                  children={(field) => (
                    <field.TextField
                      disabled={!isPublic}
                      fadeOnDisabled={!isPublic ? false : undefined}
                      data-private={!isPublic || undefined}
                      classNameInput="data-private:text-muted-foreground"
                      Icon={!isPublic ? LockIcon : undefined}
                      classNameIcon="text-muted-foreground"
                      field={field}
                      value={!isPublic ? "Private service" : field.state.value}
                      onBlur={!isPublic ? undefined : field.handleBlur}
                      onChange={
                        !isPublic
                          ? undefined
                          : (e) => {
                              field.handleChange(e.target.value);
                            }
                      }
                      showUndo={
                        isPublic && detectedPort !== undefined && field.state.value !== detectedPort
                      }
                      onUndo={() => {
                        if (detectedPort !== undefined) {
                          field.handleChange(detectedPort);
                        }
                      }}
                      placeholder="3000"
                      autoCapitalize="off"
                      autoCorrect="off"
                      autoComplete="off"
                      spellCheck="false"
                      inputMode="numeric"
                    />
                  )}
                />
              )}
            />
          </BlockItemContent>
        </BlockItem>
      </Block>
    );
  },
});

export default DomainPortBlock;
